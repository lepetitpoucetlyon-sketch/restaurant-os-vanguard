import React, { useState } from 'react';

interface AIPatch {
  id: string;
  ticketId: string;
  description: string;
  codeDiff: string;
  confidenceScore: number;
  status: 'PENDING' | 'DEPLOYED' | 'REJECTED';
}

export const AIWorkshop: React.FC = () => {
  const [patches, setPatches] = useState<AIPatch[]>([]);

  const handleDeployPatch = (patchId: string) => {
    setPatches(currentPatches =>
      currentPatches.map(patch =>
        patch.id === patchId ? { ...patch, status: 'DEPLOYED' } : patch
      )
    );
  };

  const handleRejectPatch = (patchId: string) => {
    setPatches(currentPatches =>
      currentPatches.map(patch =>
        patch.id === patchId ? { ...patch, status: 'REJECTED' } : patch
      )
    );
  };

  return (
    <div className="p-6 bg-gray-900 text-white rounded-lg shadow-xl">
      <h2 className="text-2xl font-bold mb-4 text-blue-400">MCC AI Workshop</h2>
      <p className="mb-6 text-gray-300">Validate and deploy neural patches generated by NAM.</p>

      <div className="space-y-4">
        {patches.length === 0 ? (
          <p className="text-gray-500 italic">No pending AI patches in queue.</p>
        ) : (
          patches.map(patch => (
            <div key={patch.id} className="border border-gray-700 p-4 rounded bg-gray-800">
              <div className="flex justify-between items-center mb-2">
                <h3 className="text-lg font-semibold text-green-400">Patch #{patch.id}</h3>
                <span className="text-sm bg-blue-900 text-blue-200 py-1 px-2 rounded">
                  Confidence: {(patch.confidenceScore * 100).toFixed(0)}%
                </span>
              </div>
              <p className="text-sm text-gray-400 mb-2">Ticket ID: {patch.ticketId}</p>
              <p className="mb-4">{patch.description}</p>
              <pre className="bg-black p-3 rounded text-xs text-green-300 overflow-x-auto mb-4">
                {patch.codeDiff}
              </pre>
              <div className="flex space-x-3">
                <button
                  onClick={() => handleDeployPatch(patch.id)}
                  disabled={patch.status !== 'PENDING'}
                  className="bg-green-600 hover:bg-green-700 px-4 py-2 rounded font-bold disabled:opacity-50"
                >
                  DEPLOY PATCH
                </button>
                <button
                  onClick={() => handleRejectPatch(patch.id)}
                  disabled={patch.status !== 'PENDING'}
                  className="bg-red-600 hover:bg-red-700 px-4 py-2 rounded font-bold disabled:opacity-50"
                >
                  REJECT
                </button>
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
};
